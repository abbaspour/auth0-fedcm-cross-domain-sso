#!/usr/bin/env bash

set -ueo pipefail

DIR="${BASH_SOURCE[0]%/*}"
[ "$DIR" = "${BASH_SOURCE[0]}" ] && DIR="."
readonly DIR

command -v terraform >/dev/null || { echo >&2 "error: terraform not found"; exit 3; }
command -v jq >/dev/null        || { echo >&2 "error: jq not found";        exit 3; }

function usage() {
    cat <<END >&2
USAGE: $0 [-i tf_dir] [-h]
        -i dir         # terraform directory (default ${DIR}/../tf)
        -h|?           # usage

Writes non-secret config from terraform outputs to:
    workers/idp/src/config.generated.js
    apps/spa/public/config.js

eg,
     $0 -i ./tf
END
    exit $1
}

declare TF_DIR="${DIR}/../tf"

while getopts ":i:h?" opt; do
    case ${opt} in
    i) TF_DIR=${OPTARG} ;;
    h | ?) usage 0 ;;
    \?) [[ "${OPTARG}" == "?" ]] && usage 0
        echo >&2 "ERROR: illegal option -- ${OPTARG}"
        usage 1 ;;
    :) echo >&2 "ERROR: option requires an argument -- ${OPTARG}"; usage 1 ;;
    esac
done

[[ -d "${TF_DIR}" ]] || { echo >&2 "ERROR: terraform dir missing: ${TF_DIR}"; usage 1; }

outputs=$(terraform -chdir="${TF_DIR}" output -json)
readonly outputs

[[ $(jq -r '.auth0_origin.value // empty' <<< "${outputs}") ]] \
    || { echo >&2 "ERROR: terraform outputs missing; run 'make infra' first"; exit 1; }

worker_config=$(jq '
    def app($host; $name): {
        name: $name,
        origins: ["https://\($host)"],
        privacy_policy_url: "https://\($host)/#privacy",
        terms_of_service_url: "https://\($host)/#terms"
    };
    {
        idpHost: .idp_domain.value,
        auth0Origin: .auth0_origin.value,
        bridgeClientId: .bridge_client_id.value,
        rpClients: {
            (.login_app_client_id.value): app(.login_app_host.value; "Login app (\(.login_app_host.value))"),
            (.rp_app_client_id.value): app(.rp_app_host.value; "FedCM app (\(.rp_app_host.value))")
        }
    }' <<< "${outputs}")
readonly worker_config

spa_config=$(jq '{
        idpDomain: .idp_domain.value,
        apps: {
            (.login_app_host.value): {
                name: "Login app (\(.login_app_host.value))",
                clientId: .login_app_client_id.value,
                mode: "redirect"
            },
            (.rp_app_host.value): {
                name: "FedCM app (\(.rp_app_host.value))",
                clientId: .rp_app_client_id.value,
                mode: "fedcm"
            }
        }
    }' <<< "${outputs}")
readonly spa_config

cat > "${DIR}/../workers/idp/src/config.generated.js" <<EOL
// Generated by scripts/gen-config.sh from terraform outputs. Do not edit.
export default ${worker_config};
EOL

cat > "${DIR}/../apps/spa/public/config.js" <<EOL
// Generated by scripts/gen-config.sh from terraform outputs. Do not edit.
window.FEDCM_DEMO = ${spa_config};
EOL

echo >&2 "wrote workers/idp/src/config.generated.js and apps/spa/public/config.js"
